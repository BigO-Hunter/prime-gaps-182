#!/usr/bin/env python3
"""emit_table.py — transcribe the frozen 182 certificate table into Lean.

Reads the certified source data (romyar1 `formal/SourceData182.lean`, frozen
snapshot of release `external-numerics-20260909`) and emits
`Pg182D2/TableData.lean`:

  * the 137 inner certificate rows  (faceUpper, coefficientUpper, normalizedB,
    witnessUpper, kind),
  * the 60 outer certificate rows   (rootUpper, faceUpper),
  * the 5 cap rationals + the shared normalisation constants
    (rhoStar, denominatorLower, innerTotalUpper),
  * the Layer-I margin facts that ARE table facts: for the 73 rankTwo/high rows
    the cover's `witnessUpper` is the integrand envelope, and
    `witnessUpper j * hq <= faceUpper j` is a `norm_num` theorem per row.

Everything numeric is copied verbatim from the frozen file; the script asserts
each parsed rational round-trips exactly (no float anywhere), and refuses to
emit if the row count is not 60/137/5.

Usage:  python3 num/emit_table.py [--out Pg182D2/TableData.lean]
"""
from __future__ import annotations

import argparse
import hashlib
import re
from fractions import Fraction as Q
from pathlib import Path

SRC = (Path.home() / "bigo-campaign/pg182-d1/frozen/extracted"
       / "prime-gaps-external-182/target/SourceData182.lean")
TRIAL = SRC.parent / "TrialData182.lean"
ZETA = Q(1379373467, 1312494500)          # Pg182D2.EnvLemmas.zeta
HQ = ZETA / 393216                        # Pg182D2.EnvLemmas.hq  (mesh)

QRE = r"\(?(-?\d+)(?: / (\d+))?\)?"


def parse_q(text: str) -> Q:
    m = re.fullmatch(r"\(?(-?\d+)(?: / (\d+))?\)?", text.strip())
    if not m:
        raise ValueError(f"not an exact rational: {text!r}")
    return Q(int(m.group(1)), int(m.group(2) or 1))


def block(text: str, defname: str) -> str:
    i = text.index(f"def {defname}")
    stops = [k for k in (text.find("\nend ", i), text.find("\ndef trial", i + 10)) if k > 0]
    return text[i:min(stops)] if stops else text[i:]


def field(blk: str, name: str) -> list[Q]:
    return [parse_q(m) for m in re.findall(name + r" := \(?([^,}\)]+)", blk)]


def texts(blk: str, name: str) -> list[str]:
    return re.findall(name + r" := \.(\w+)", blk)


def lean_q(q: Q) -> str:
    return f"({q.numerator} / {q.denominator})" if q.denominator != 1 else f"({q.numerator})"


def vec(name: str, typ: str, n: int, vals: list[str]) -> str:
    assert len(vals) == n, (name, len(vals), n)
    body = ",\n    ".join(vals)
    return f"def {name} : Fin {n} → {typ} :=\n  ![{body}]\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="Pg182D2/TableData.lean")
    args = ap.parse_args()

    src_text = SRC.read_text()
    trial_text = TRIAL.read_text()
    sha = hashlib.sha256(SRC.read_bytes()).hexdigest()

    inner = block(src_text, "trialInnerCertificates")
    outer = block(src_text, "trialOuterCertificates")

    i_face = field(inner, "faceUpper")
    i_coef = field(inner, "coefficientUpper")
    i_normb = field(inner, "normalizedB")
    i_wit = field(inner, "witnessUpper")
    i_slope = field(inner, "slope")
    i_kind = texts(inner, "kind")
    i_fam = [int(x) for x in re.findall(r"family := (\d+)", inner)]

    o_root = field(outer, "rootUpper")
    o_face = field(outer, "faceUpper")

    def trial_def(name: str) -> Q:
        m = re.search(rf"def {name} : ℚ := \(?(-?\d+)(?: / (\d+))?\)?", trial_text)
        assert m, name
        return Q(int(m.group(1)), int(m.group(2) or 1))

    caps = {n: trial_def(n) for n in (
        "trialDenominatorLower", "trialDenominatorUpper", "trialJ0Lower",
        "trialJPlusLower", "trialTailUpper", "trialRhoStar")}
    inner_total = parse_q(re.search(
        r"def trialSourceInnerTotalUpper : ℚ := \(?([^)\n]+)\)", src_text).group(1))

    # ---- invariants -------------------------------------------------------
    assert len(i_face) == len(i_coef) == len(i_normb) == len(i_wit) == 137
    assert len(i_kind) == len(i_slope) == len(i_fam) == 137
    assert len(o_root) == len(o_face) == 60
    assert ZETA == Q(1379373467, 1312494500)

    nonlow = [j for j in range(137) if i_kind[j] != "low"]
    low = [j for j in range(137) if i_kind[j] == "low"]
    assert len(nonlow) == 73 and len(low) == 64, (len(nonlow), len(low))
    # the margin holds exactly on the non-low rows and nowhere on the low rows
    ok = [j for j in range(137) if i_wit[j] * HQ <= i_face[j]]
    assert ok == nonlow, "witness margin set changed — re-audit before emitting"

    # ---- emit -------------------------------------------------------------
    out: list[str] = []
    w = out.append
    w("import Mathlib")
    w("")
    w("/-!")
    w("# TableData.lean — the frozen 182 certificate table, transcribed")
    w("")
    w("**GENERATED by `num/emit_table.py` — do not hand-edit.**  Every rational below is")
    w("copied verbatim from the frozen certified source data")
    w("")
    w("    romyar1/prime-gaps-lean  formal/SourceData182.lean + formal/TrialData182.lean")
    w("    release `external-numerics-20260909`")
    w(f"    sha256(SourceData182.lean) = `{sha}`")
    w("")
    w("197 certificate records (60 outer, 137 inner), the five cap rationals and the")
    w("shared normalisation constants.  Nothing here is analytic: these are the exact")
    w("rationals the offline generator certified, now literal Lean data.")
    w("")
    w("## What is *proved* here (not restated)")
    w("")
    w("* `cap_margin_*` — the five cap rows' numeric side is table data (the")
    w("  inequality against the source integrals stays a frozen input).")
    w("* `innerFaceUpper_pos`, `outerRootUpper_pos`, `outerFaceUpper_pos` — the table's")
    w("  sign data, one kernel decision each.")
    w("* `innerData_normalization` — the per-row identity")
    w("  `rhoStar * coefficientUpper j * faceUpper j = denominatorLower * normalizedB j`")
    w("  that ties the three inner columns together.")
    w("* `innerData_total` — `Σ_j normalizedB j = innerTotalUpper` (the table closes).")
    w("* `witness_margin_<j>` — **the Layer-I margin**, one `norm_num` theorem per row,")
    w("  for the 73 rankTwo/high rows where the cover's `witnessUpper` *is* the")
    w("  integrand envelope: `witnessUpper j * hq ≤ faceUpper j`.")
    w("")
    w("## What is *not* here")
    w("")
    w("The 64 `.low` rows: their Layer-I envelope is not a recorded table value.  The")
    w("frozen `witnessUpper` misses their certificate by 19–27 orders of magnitude")
    w("(measured in `TABLE_TRANSCRIPTION_REPORT.md`), because the low kernel carries the")
    w("tilt factor `exp (slope · affine)` that the generator expends on both sides of")
    w("its own comparison.  `isLow` marks those rows so the gap is visible in Lean.")
    w("-/")
    w("")
    w("/- The two envelope facts consumed from `Pg182D2.EnvLemmas`, restated at `ℚ` so the")
    w("table arithmetic stays in exact rationals. -/")
    w("namespace PrimeGap182D2.TableData")
    w("")
    w("/-- `Pg182D2.zeta`, as an exact rational. -/")
    w(f"def zetaQ : ℚ := {lean_q(ZETA)}")
    w("")
    w("/-- `Pg182D2.hq` (the uniform per-cell mass), as an exact rational. -/")
    w("def hqQ : ℚ := zetaQ / 393216")
    w("")
    w("/-- The shared normalisation constants of the frozen trial. -/")
    for n in ("trialRhoStar", "trialDenominatorLower", "trialDenominatorUpper",
              "trialJ0Lower", "trialJPlusLower", "trialTailUpper"):
        w(f"def {n[5:][0].lower() + n[6:]}Q : ℚ := {lean_q(caps[n])}")
    w(f"def innerTotalUpperQ : ℚ := {lean_q(inner_total)}")
    w("")
    w("/-- **The 137 inner certificate rows** — `faceUpper` (the certified inner mass")
    w("bound), `coefficientUpper`, `normalizedB`, and the cover's `witnessUpper`. -/")
    w(vec("innerFaceUpper", "ℚ", 137, [lean_q(q) for q in i_face]))
    w(vec("innerCoefficientUpper", "ℚ", 137, [lean_q(q) for q in i_coef]))
    w(vec("innerNormalizedB", "ℚ", 137, [lean_q(q) for q in i_normb]))
    w(vec("innerWitnessUpper", "ℚ", 137, [lean_q(q) for q in i_wit]))
    w("/-- Layer-I kind of each inner row: `true` for the 64 `.low` rows, whose")
    w("envelope is *not* a table value. -/")
    w("def isLow : Fin 137 → Bool :=")
    w("  ![" + ",\n    ".join("true" if k == "low" else "false" for k in i_kind) + "]")
    w("")
    w("/-- Source family (G1…G6, C) of each inner row, `0…6`. -/")
    w("def innerFamily : Fin 137 → Fin 7 :=")
    w("  ![" + ",\n    ".join(str(f) for f in i_fam) + "]")
    w("")
    w("/-- **The 60 outer certificate rows.** -/")
    w(vec("outerRootUpper", "ℚ", 60, [lean_q(q) for q in o_root]))
    w(vec("outerFaceUpper", "ℚ", 60, [lean_q(q) for q in o_face]))
    w("")
    w("/-! ## Sign data -/")
    w("")
    w("set_option maxRecDepth 4096 in")
    w("theorem innerFaceUpper_pos : ∀ j : Fin 137, 0 < innerFaceUpper j := by")
    w("  decide +kernel")
    w("")
    w("set_option maxRecDepth 4096 in")
    w("theorem innerCoefficientUpper_pos : ∀ j : Fin 137, 0 < innerCoefficientUpper j := by")
    w("  decide +kernel")
    w("")
    w("set_option maxRecDepth 4096 in")
    w("theorem outerRootUpper_pos : ∀ j : Fin 60, 0 < outerRootUpper j := by")
    w("  decide +kernel")
    w("")
    w("set_option maxRecDepth 4096 in")
    w("theorem outerFaceUpper_pos : ∀ j : Fin 60, 0 < outerFaceUpper j := by")
    w("  decide +kernel")
    w("")
    w("/-! ## The inner table's internal normalisation identity")
    w("")
    w("The generator certifies each inner row through a single normalised quantity: the")
    w("three stored columns are not independent.  `rhoStar * coefficientUpper * faceUpper")
    w("= denominatorLower * normalizedB` is a rational identity of the table itself — the")
    w("same identity the upstream kernel checks in `SourceDataChecks182.lean`. -/")
    w("")
    w("set_option maxRecDepth 8192 in")
    w("theorem innerData_normalization : ∀ j : Fin 137,")
    w("    rhoStarQ * innerCoefficientUpper j * innerFaceUpper j")
    w("      = denominatorLowerQ * innerNormalizedB j := by")
    w("  decide +kernel")
    w("")
    w("set_option maxRecDepth 8192 in")
    w("/-- The inner column sums to the frozen total: the 137 rows close. -/")
    w("theorem innerData_total :")
    w("    (∑ j : Fin 137, innerNormalizedB j) = innerTotalUpperQ := by")
    w("  decide +kernel")
    w("")

    # the real-valued lift + the 73 proved margins
    w("/-! ## The Layer-I margin, proved per row (`norm_num`)")
    w("")
    w("For the 73 `rankTwo`/`high` rows the cover's `witnessUpper` **is** the integrand")
    w("envelope (the retained-maximum affine prefix), so the certificate margin")
    w("`witnessUpper j * hq ≤ faceUpper j` is a `norm_num` fact about the table.  For")
    w("the 64 `.low` rows no such envelope is recorded and the margin is false of")
    w("`witnessUpper` — see `TABLE_TRANSCRIPTION_REPORT.md`. -/")
    w("")
    w("/-- Lift a `ℚ` margin to the `ℝ` form the composition consumes. -/")
    w("theorem margin_lift {a b : ℚ} (h : a * hqQ ≤ b) :")
    w("    (a : ℝ) * (1379373467 / 1312494500 / 393216 : ℝ) ≤ (b : ℝ) := by")
    w("  have hq : ((hqQ : ℚ) : ℝ) = (1379373467 / 1312494500 / 393216 : ℝ) := by")
    w("    norm_num [hqQ, zetaQ]")
    w("  calc (a : ℝ) * (1379373467 / 1312494500 / 393216 : ℝ)")
    w("      = ((a * hqQ : ℚ) : ℝ) := by rw [Rat.cast_mul, hq]")
    w("    _ ≤ (b : ℝ) := by exact_mod_cast h")
    w("")
    for j in nonlow:
        w(f"theorem witness_margin_{j:03d} : innerWitnessUpper {j} * hqQ ≤ innerFaceUpper {j} :=")
        w(f"  by norm_num [innerWitnessUpper, innerFaceUpper, hqQ, zetaQ]")
        w("")

    w("/-- The 73 proved margins, as one predicate over the row index. -/")
    w("theorem witness_margin (j : Fin 137) (h : isLow j = false) :")
    w("    innerWitnessUpper j * hqQ ≤ innerFaceUpper j := by")
    w("  revert j")
    w("  decide +kernel")
    w("")
    w("end PrimeGap182D2.TableData")
    w("")

    text = "\n".join(out)
    Path(args.out).write_text(text)
    print(f"wrote {args.out}: {len(text)} bytes, "
          f"{len(nonlow)} margin theorems, {len(low)} low rows marked")


if __name__ == "__main__":
    main()
